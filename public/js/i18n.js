/* ---------- helpers ---------- */
function currentLang() {
  const l = localStorage.getItem('pds_lang');
  return (l === 'my' || l === 'en') ? l : 'en';
}

function t(key, vars) {
  const lang = currentLang();
  const dict = I18N[lang] || I18N.en;
  let s = (dict[key] !== undefined) ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  if (vars && typeof s === 'string') {
    for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  }
  return s;
}

function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  scope.querySelectorAll('[data-i18n-ph]').forEach(el => { el.setAttribute('placeholder', t(el.dataset.i18nPh)); });
  scope.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.documentElement.lang = currentLang() === 'my' ? 'my' : 'en';
  document.querySelectorAll('.lang-switch button').forEach(b => {
    b.classList.toggle('on', b.dataset.lang === currentLang());
  });
}

function setLang(l) {
  if (l !== 'my' && l !== 'en') l = 'en';
  localStorage.setItem('pds_lang', l);
  applyI18n();
  /* persist server-side when logged in; ignore failures (guest / logged out) */
  if (typeof api === 'function') {
    api('/api/auth/profile', { method: 'PUT', body: { lang: l } }).catch(() => {});
  }
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: l } }));
}
